    def evaluate(self, board: chess.Board) -> int:
        
        if board.is_checkmate():
            return -99999 if board.turn == chess.WHITE else 99999
        if board.is_stalemate() or board.is_insufficient_material():
            return 0

        score = 0
        
        
        for square in chess.SQUARES:
            piece = board.piece_at(square)
            if piece:
                val = self._get_piece_value(piece, square)
                if piece.color == chess.WHITE:
                    score += val
                else:
                    score -= val
        
        return score

    def _get_piece_value(self, piece: chess.Piece, square: chess.Square) -> int:
        
        base_val = self.PIECE_VALUES.get(piece.piece_type, 0)
        
        
        pst_index = square
        if piece.color == chess.BLACK:
            
            pst_index = chess.SQUARE_NAMES.index(chess.square_name(square))
            
            pst_index = (7 - (square // 8)) * 8 + (square % 8)

        positional_val = self.PST[piece.piece_type][pst_index]
        
        return base_val + positional_val

